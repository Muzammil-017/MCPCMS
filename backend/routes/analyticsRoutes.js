const express = require('express');
const router = express.Router();
const { getOverview, getPayrollTrends, getDepartmentSalary, getCompanyComparison, getComplianceStatus, getAttendanceSummary } = require('../controllers/analyticsController');
const { protect, companyStaffOnly } = require('../middleware/authMiddleware');
router.use(protect, companyStaffOnly);
router.get('/overview', getOverview);
router.get('/payroll-trends', getPayrollTrends);
router.get('/department-salary', getDepartmentSalary);
router.get('/company-comparison', getCompanyComparison);
router.get('/compliance-status', getComplianceStatus);
router.get('/attendance-summary', getAttendanceSummary);
module.exports = router;
