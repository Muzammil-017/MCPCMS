const express = require('express');
const router = express.Router();
const { markAttendance, markBulkAttendance, getAttendance, getAttendanceSummary, deleteAttendance } = require('../controllers/attendanceController');
const { protect, companyStaffOnly } = require('../middleware/authMiddleware');
router.use(protect, companyStaffOnly);
router.post('/', markAttendance);
router.post('/bulk', markBulkAttendance);
router.get('/', getAttendance);
router.get('/summary', getAttendanceSummary);
router.delete('/:id', deleteAttendance);
module.exports = router;
