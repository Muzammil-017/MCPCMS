const express = require('express');
const router = express.Router();
const { markAttendance, markBulkAttendance, getAttendance, getAttendanceSummary, deleteAttendance } = require('../controllers/attendanceController');
const { protect } = require('../middleware/authMiddleware');
router.post('/', protect, markAttendance);
router.post('/bulk', protect, markBulkAttendance);
router.get('/', protect, getAttendance);
router.get('/summary', protect, getAttendanceSummary);
router.delete('/:id', protect, deleteAttendance);
module.exports = router;
