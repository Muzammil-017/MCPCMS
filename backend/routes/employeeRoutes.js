const express = require('express');
const router = express.Router();
const { createEmployee, bulkCreateEmployees, getEmployees, getEmployee, updateEmployee, deleteEmployee, getDepartments, resetEmployeePassword } = require('../controllers/employeeController');
const { protect, companyStaffOnly } = require('../middleware/authMiddleware');
router.use(protect, companyStaffOnly);
router.post('/', createEmployee);
router.post('/bulk', bulkCreateEmployees);
router.get('/', getEmployees);
router.get('/departments', getDepartments);
router.get('/:id', getEmployee);
router.put('/:id', updateEmployee);
router.put('/:id/password', resetEmployeePassword);
router.delete('/:id', deleteEmployee);
module.exports = router;
